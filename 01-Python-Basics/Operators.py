#arithemtic operators

a =10
b=5
print("Addition:",a+b)
print("Subtraction:",a-b)
print("Multiplication:",a*b)
print("Division:",a/b)
print("Modulus:",a%b)
print("Floor division:",a//b)
print("Exponent:",a**b)

#comparison operators

print("\n Equal:",a==b)
print("Not equal:",a!=b)
print("Greater than",a>b)
print("Less than",a<b)
print("Greater than equal to",a>=b)
print("less than  equal to",a<=b)

#logical operator

x = True
y = False

print("AND",x and y)
print("OR",x or y)
print("NOT",not y)

#assignment operators
c =10
c+=5
print("After +=",c)
c-=7
print("After -=",c)
c*=2
print("After *=",c)
c/=9
print("After /=",c)

#membership operators

number=[10,20,30,40,50]
print("20 in numbers:",20 in number)
print("50 not in numbers",50 not in number)

#identity operators

p=[1,2,3]
q=p
r=[1,2,3]
print("p is q",p is q)
print("p is r",p is r)
print("p is not r",p is not r)


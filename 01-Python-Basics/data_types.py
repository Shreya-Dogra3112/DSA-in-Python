# Data types in Python

#Integer

age=19
print("Integer:",age)
print(type(age))

#Float
price = 95.9
print("Float",price)
print(type(price))

# boolean
ans = True
print("Boolean",ans)
print(type(ans))

# string
name="Shreya"
name1='shreya'
print("name",name)
print("other name:",name1)
print(type(name))
print(type(name1))

#set
set1={1,"hello",56.90}
print("set values are",set1)
print(type(set1))

#list
list1=[1,6,9]
print("list is ",list1)
print(type(list1))

#dictionary
dict1={
    name:"shreya",
    
}
